import type { ChunkSource } from './chunk';
import { logger } from './utils';

// Brush's `SplatRenderMode: <mode>` (brush-serde export.rs/import.rs) — the wire
// form we also write, see `splatModelComment` in the writers.
const MODE_COMMENT_KEY = 'splatrendermode: ';

// Postshot's flag (v1.0.110 to v1.1.69 write `postshot.anti_aliasing=1`, and omit it without anti-aliasing).
const AA_COMMENT_KEY = 'postshot.anti_aliasing=';

/**
 * The producer comments a scene carries: all but the PLY model tags (read into
 * the model, and written back from it) and splat-transform's own generator line
 * (written afresh). Applied when reading a PLY and again when writing one, so a
 * round trip does not repeat them and a comment from elsewhere (a SOG meta.json,
 * say) cannot override the scene's model.
 *
 * @param comments - Comments, without a leading `comment `.
 * @returns The comments to keep.
 */
const producerComments = (comments: readonly string[]): string[] => {
    return comments.filter((comment) => {
        const lower = comment.toLowerCase().trim();
        return (
            !lower.startsWith(MODE_COMMENT_KEY) &&
            !lower.startsWith(AA_COMMENT_KEY) &&
            !lower.startsWith('generated by splat-transform')
        );
    });
};

/**
 * The same source with `meta.comments` replaced (or removed when `comments` is
 * undefined or empty). Reads are untouched.
 *
 * @param source - The source.
 * @param comments - The producer comments to attach.
 * @returns A source carrying `comments`.
 */
const withComments = (source: ChunkSource, comments: readonly string[] | undefined): ChunkSource => {
    if (source.meta.comments === comments) return source;
    const { comments: _, ...meta } = source.meta;
    // delegate rather than spread: sources may be class instances
    return {
        meta: comments?.length ? { ...meta, comments } : meta,
        read: (request) => source.read(request),
        close: () => source.close()
    };
};

/**
 * The comments of a combined scene: kept when every input carries the same
 * comments (or none), dropped with a warning when they disagree.
 *
 * @param sources - The sources being combined.
 * @returns The agreed comments, or undefined.
 */
const resolveComments = (sources: readonly ChunkSource[]): readonly string[] | undefined => {
    const keys = sources.map((s) => JSON.stringify(s.meta.comments ?? []));
    if (keys.every((k) => k === keys[0])) return sources[0]?.meta.comments;
    logger.warn('inputs carry different comments; the combined scene keeps none');
    return undefined;
};

export { AA_COMMENT_KEY, MODE_COMMENT_KEY, producerComments, withComments, resolveComments };
